"""
experiments.py — the experiment engine.

    ExperimentDefinition (plain JSON) --run()--> ExperimentResult (plain JSON)

A definition says WHAT to test; it contains no code and no UI state, so it
can be saved, re-run, forked, compared across tickers, generated by AI
later, or replayed bar-by-bar, all with this same engine:

{
  "version": 1,
  "instrument": {"symbol": "NVDA", "asset_class": "equity"},
  "timeframe": "1d",
  "conditions": [ {"id": "c1", "type": "price_move", "params": {...}}, ... ],
  "logic": {"op": "AND", "items": ["c1", "c2"]},                   # AND today; OR-ready
  "outcome": {"type": "forward_return", "horizon": 10},
  "period": {"start": null, "end": null},                           # null = all available
  "benchmark": "SPY",
  "settings": {"overlap": "non_overlapping", "entry": "close", "trim": 0.05}
}

=============================================================================
METHODOLOGY
=============================================================================
1. PRICES: daily closes adjusted for splits and dividends, validated by
   dataquality.py (unadjusted splits corrected, bad prints removed, real
   extreme moves kept). Returns are therefore total returns.
2. TRADING DAYS: one row = one trading day. P(t) = adjusted close on day t.
3. TRIGGER DETECTION (no look-ahead): day t qualifies when the logic over
   the conditions is true using data up to and including day t's close.
   detect_triggers() never sees forward prices.
4. OUTCOME MEASUREMENT (separate step): R(t) = P(t + H) / P(t) − 1, from
   the trigger day's close (assumes you could act at that close: slightly
   optimistic). measure_outcomes() is the only code that reads prices after t.
5. NO DOUBLE COUNTING: after an episode at t, the next can't start before
   t + H + 1. Forward windows never overlap; in a cluster of qualifying
   days, only the first counts.
6. INCOMPLETE: if t + H is past the last bar, the episode is "in progress"
   and excluded from statistics.
7. GAPS: windows crossing a >10-calendar-day data gap are skipped.
8. BASELINE: the H-day return from every day in the same evaluable range
   (overlapping, so descriptive only).
9. STATISTICS: conventional (mean, median, std, t-interval) AND robust
   (trimmed, winsorized, without-most-extreme, bootstrap) side by side,
   plus factual robustness checks. Nothing is deleted for being extreme.
10. Past frequencies are not predictions; testing many ideas on the same
   history will eventually find something that "worked" by chance.
"""

import copy
import json
from datetime import date

import conditions
import dataquality
import marketdata
import robust
from data import now_iso

VERSION = 2
MAX_GAP_DAYS = 10
MAX_CONDITIONS = 6
SMALL_SAMPLE, MODERATE_SAMPLE = 10, 30
SUPPORTED_TIMEFRAMES = {"1d"}          # intraday ("5m", "1h"...) plugs in via marketdata later


class LabInputError(ValueError):
    """The experiment definition is invalid or the history is too short."""


def default_definition(symbol="NVDA"):
    return {
        "version": VERSION,
        "instrument": {"symbol": symbol, "asset_class": "equity"},
        "timeframe": "1d",
        "conditions": [{"id": "c1", "type": "price_move", "params": {"direction": "falls", "threshold": 5, "window": 5}}],
        "logic": None,
        "outcome": {"type": "forward_return", "horizon": 10},
        "period": {"start": None, "end": None},
        "benchmark": "SPY",
        "settings": {"overlap": "non_overlapping", "entry": "close", "trim": 0.05},
    }


def normalize(raw):
    """Validate a definition and fill defaults. Raises LabInputError with a readable message."""
    if not isinstance(raw, dict):
        raise LabInputError("Experiment definition must be an object.")
    d = default_definition()
    d.update({k: copy.deepcopy(v) for k, v in raw.items() if k in d})
    d["version"] = VERSION
    symbol = str((d["instrument"] or {}).get("symbol", "")).strip().upper()
    if not symbol or len(symbol) > 12:
        raise LabInputError("Choose a ticker to test.")
    d["instrument"] = {"symbol": symbol, "asset_class": (d["instrument"] or {}).get("asset_class", "equity")}
    if d["timeframe"] not in SUPPORTED_TIMEFRAMES:
        raise LabInputError(f"Timeframe {d['timeframe']!r} isn't supported yet (daily only for now).")
    if not d["conditions"]:
        raise LabInputError("Add at least one condition.")
    if len(d["conditions"]) > MAX_CONDITIONS:
        raise LabInputError(f"Up to {MAX_CONDITIONS} conditions per experiment.")
    try:
        clean, seen = [], set()
        for i, c in enumerate(d["conditions"]):
            v = conditions.validate(c, i)
            if v["id"] in seen:                     # ids must be unique for the logic tree
                v["id"] = f"c{i + 1}_{len(seen)}"
            seen.add(v["id"])
            clean.append(v)
        d["conditions"] = clean
        d["logic"] = conditions.validate_logic(d.get("logic"), [c["id"] for c in clean])
    except ValueError as error:
        raise LabInputError(str(error)) from error
    horizon = d["outcome"].get("horizon")
    try:
        horizon = int(horizon)
    except (TypeError, ValueError):
        raise LabInputError("Forward period must be a whole number of trading days.")
    if not 1 <= horizon <= 252:
        raise LabInputError("Forward period must be between 1 and 252 trading days.")
    d["outcome"] = {"type": "forward_return", "horizon": horizon}
    period = d.get("period") or {}
    d["period"] = {"start": period.get("start") or None, "end": period.get("end") or None}
    trim = float((d["settings"] or {}).get("trim", 0.05))
    d["settings"] = {"overlap": "non_overlapping", "entry": "close", "trim": min(max(trim, 0.0), 0.2)}
    return d


def _days(a, b):
    return (date.fromisoformat(b) - date.fromisoformat(a)).days


# =============================================================================
# STEP 1 — prepare: data + every condition evaluated once (cached)
# =============================================================================
_series_cache = {}   # (id(bars), condition json) -> series


def _series(condition, bars, ctx):
    key = (id(bars), json.dumps({k: condition[k] for k in ("type", "params")}, sort_keys=True))
    if key not in _series_cache:
        if len(_series_cache) > 300:
            _series_cache.clear()
        _series_cache[key] = conditions.compute(condition, bars, ctx)
    return _series_cache[key]


def prepare(definition):
    """Load bars, evaluate conditions, work out the testable range. No forward prices are used."""
    symbol = definition["instrument"]["symbol"]
    horizon = definition["outcome"]["horizon"]
    conds = definition["conditions"]
    bars = marketdata.daily_bars(symbol)
    dates = bars["date"]
    count = len(dates)
    ctx = conditions.Context(symbol)

    start, end = definition["period"].get("start"), definition["period"].get("end")
    first_allowed = next((i for i, d in enumerate(dates) if not start or d >= start), count)
    last_allowed = max((i for i, d in enumerate(dates) if not end or d <= end), default=-1)

    warm = max(conditions.warmup(c) for c in conds)
    needed = warm + horizon + 20
    if count < needed:
        raise LabInputError(f"{symbol} has only {count} trading days of history; this experiment needs at least {needed}.")
    if last_allowed - max(warm, first_allowed) < horizon + 5:
        raise LabInputError("The chosen date range is too short for this forward period.")

    gaps = [0] * count
    for i in range(1, count):
        gaps[i] = gaps[i - 1] + (1 if _days(dates[i - 1], dates[i]) > MAX_GAP_DAYS else 0)

    try:
        series = {c["id"]: _series(c, bars, ctx) for c in conds}
    except Exception as error:   # e.g. earnings dates unavailable
        raise LabInputError(f"Couldn't evaluate a condition: {error}") from error
    combined = conditions.combine(definition["logic"], series, count)
    return {"definition": definition, "symbol": symbol, "bars": bars, "ctx": ctx, "series": series,
            "combined": combined, "warm": warm, "first": max(warm, first_allowed), "last": last_allowed,
            "gaps": gaps}


def _has_gap(prep, a, b):
    return prep["gaps"][b] - prep["gaps"][a] > 0


# =============================================================================
# STEP 2 — trigger detection (uses only information up to each day's close)
# =============================================================================
def detect_triggers(prep, horizon):
    """
    Returns (episodes, qualifying_days, skipped_for_gaps).
    episodes: [{"index": t, "status": "complete"|"pending"}]
    Non-overlapping: after an episode at t, the next can't start before t + horizon + 1.
    `horizon` is only used to space episodes and to know which are still in progress;
    no price after t is read here.
    """
    combined, warm, last = prep["combined"], prep["warm"], prep["last"]
    episodes, qualifying, skipped = [], 0, 0
    next_allowed = prep["first"]
    for t in range(prep["first"], last + 1):
        if not combined[t]:
            continue
        qualifying += 1
        if t < next_allowed:
            continue
        lookback_start = max(0, t - warm)
        exit_index = t + horizon
        if exit_index > last:
            if not _has_gap(prep, lookback_start, last):
                episodes.append({"index": t, "status": "pending"})
            next_allowed = last + 1
            continue
        if _has_gap(prep, lookback_start, exit_index):
            skipped += 1
            continue
        episodes.append({"index": t, "status": "complete"})
        next_allowed = exit_index + 1
    return episodes, qualifying, skipped


# =============================================================================
# STEP 3 — outcome measurement (the only place forward prices are read)
# =============================================================================
def measure_outcomes(prep, episodes, horizon, benchmark=None, with_details=True):
    bars = prep["bars"]
    dates, closes = bars["date"], bars["close"]
    bench_close = dict(zip(benchmark["date"], benchmark["close"])) if benchmark else {}
    price_cond = next((c for c in prep["definition"]["conditions"] if c["type"] == "price_move"), None)
    events = []
    for ep in episodes:
        t = ep["index"]
        e = {"trigger_date": dates[t], "entry_price": closes[t], "status": ep["status"],
             "trigger_return": conditions.price_move_value(bars, price_cond["params"], t) if price_cond else None}
        if ep["status"] == "pending":
            e.update(exit_date=None, forward_return=None, days_elapsed=prep["last"] - t)
        else:
            x = t + horizon
            e.update(exit_date=dates[x], exit_price=closes[x], forward_return=closes[x] / closes[t] - 1)
            b0, b1 = bench_close.get(dates[t]), bench_close.get(dates[x])
            e["benchmark_return"] = (b1 / b0 - 1) if (b0 and b1) else None
            if with_details:
                e["path"] = [closes[i] / closes[t] - 1 for i in range(t, x + 1)] if horizon <= 63 else None
        if with_details:
            e["measures"] = [m for m in (conditions.measure(c, bars, t, prep["ctx"]) for c in prep["definition"]["conditions"]) if m]
        events.append(e)
    return events


def baseline_returns(prep, horizon):
    """The H-day return from EVERY evaluable day in the same range (overlapping; descriptive only)."""
    closes = prep["bars"]["close"]
    return [closes[t + horizon] / closes[t] - 1
            for t in range(prep["first"], prep["last"] - horizon + 1)
            if not _has_gap(prep, max(0, t - prep["warm"]), t + horizon)]


def _benchmark_bars(symbol, benchmark):
    if not benchmark or benchmark == symbol:
        return None
    try:
        return marketdata.daily_bars(benchmark)
    except Exception:
        return None


# =============================================================================
# run(): the full experiment
# =============================================================================
def run(raw_definition):
    definition = normalize(raw_definition)
    symbol = definition["instrument"]["symbol"]
    horizon = definition["outcome"]["horizon"]

    prep = prepare(definition)
    bars = prep["bars"]
    dates = bars["date"]
    episodes, qualifying, skipped_gaps = detect_triggers(prep, horizon)
    bench = _benchmark_bars(symbol, definition["benchmark"])
    events = measure_outcomes(prep, episodes, horizon, bench)

    completed = [e for e in events if e["status"] == "complete"]
    outcomes = [e["forward_return"] for e in completed]
    stats = robust.summarize(outcomes)
    robust_part = robust.robust_stats(outcomes, definition["settings"]["trim"]) if outcomes else None
    if stats:
        best = max(completed, key=lambda e: e["forward_return"])
        worst = min(completed, key=lambda e: e["forward_return"])
        stats["best"] = {"date": best["trigger_date"], "return": best["forward_return"]}
        stats["worst"] = {"date": worst["trigger_date"], "return": worst["forward_return"]}
        robust_part["most_extreme"]["date"] = completed[robust_part["most_extreme"]["index"]]["trigger_date"]

    baseline = robust.summarize(baseline_returns(prep, horizon))
    difference = (stats["mean"] - baseline["mean"]) if (stats and baseline) else None
    median_difference = (stats["median"] - baseline["median"]) if (stats and baseline) else None
    bench_returns = [e["benchmark_return"] for e in completed if e.get("benchmark_return") is not None]

    checks = robust.robustness_checks(outcomes, [e["trigger_date"] for e in completed], stats, robust_part,
                                      baseline["mean"] if baseline else None) if stats else []

    range_start, range_end = dates[prep["first"]], dates[prep["last"]]
    quality_issues = dataquality.issues_between(bars["quality"], range_start, range_end)
    affected = {x["date"] for x in quality_issues if x["date"]}
    for e in completed:
        hits = [x for x in quality_issues if x["date"] and e["trigger_date"] <= x["date"] <= e["exit_date"]
                and x["check"] in ("extreme_move", "possible_split")]
        if hits:
            e["flags"] = [f"{x['check'].replace('_', ' ')} on {x['date']}" for x in hits]

    warnings = []
    n = stats["n"] if stats else 0
    if n == 0:
        warnings.append("No completed historical episodes matched. Loosen a condition, remove one, or lengthen the date range.")
    elif n < SMALL_SAMPLE:
        warnings.append(f"Only {n} historical episode{'s' if n != 1 else ''} matched. This result has substantial sampling uncertainty.")
    elif n < MODERATE_SAMPLE:
        warnings.append(f"{n} historical episodes matched: a modest sample. Treat averages and intervals as rough.")

    out = {
        "definition": definition,
        "ticker": symbol,
        "params": _legacy_params(definition),
        "data": {
            "first_date": dates[0], "last_date": dates[-1], "trading_days": len(dates),
            "tested_from": range_start, "tested_to": range_end,
            "adjusted": True, "source": bars["provider"], "retrieved_at": bars["retrieved_at"],
            "skipped_for_gaps": skipped_gaps,
            "quality": {"summary": bars["quality"]["summary"], "checks": bars["quality"]["checks"],
                        "issues": quality_issues, "issue_dates_in_range": len(affected)},
        },
        "qualifying_days": qualifying,
        "events": events,
        "stats": stats,
        "robust": robust_part,
        "checks": checks,
        "baseline": baseline,
        "difference": difference,
        "median_difference": median_difference,
        "benchmark": {"symbol": definition["benchmark"], "mean": sum(bench_returns) / len(bench_returns),
                      "n": len(bench_returns)} if bench_returns else None,
        "baseline_inside_ci": (stats["ci_low"] <= baseline["mean"] <= stats["ci_high"])
        if (stats and baseline and stats["ci_low"] is not None) else None,
        "warnings": warnings,
        "methodology": methodology(definition, bars, range_start, range_end, skipped_gaps),
        "ran_at": now_iso(),
    }
    out["summary"] = summary_for_notebook(out)
    return out


def methodology(definition, bars, start, end, skipped):
    """Plain-language, reproducible description of exactly what was computed."""
    H = definition["outcome"]["horizon"]
    sentences = []
    for c in definition["conditions"]:
        spec = conditions.REGISTRY[c["type"]]
        text = spec["sentence"]
        for k, v in c["params"].items():
            text = text.replace("{" + k + "}", str(v))
        sentences.append(text.replace("{symbol}", definition["instrument"]["symbol"]))
    return [
        {"title": "Price series", "text": f"{bars['provider']}, {start} to {end}. Daily closes are adjusted for splits and dividends, so returns include dividends. Every series is checked first (bad prints removed, unadjusted splits corrected, real extreme moves kept)."},
        {"title": "Trigger", "text": f"A day qualifies when {' AND '.join(sentences)}, evaluated with data up to and including that day's close. Moving averages and RSI use only past and current closes; volume averages use the days before."},
        {"title": "Overlapping episodes", "text": f"After an episode starts on day t, the next can't start until day t + {H} + 1, so forward windows never overlap. Episodes whose {H}-day window hasn't finished are shown but excluded from statistics." + (f" {skipped} were skipped because the window crossed a gap of more than {MAX_GAP_DAYS} calendar days in the data." if skipped else "")},
        {"title": "Forward return", "text": f"Close of the trigger day to the close {H} trading days later: P(t+{H}) / P(t) − 1. This assumes you could act at the trigger day's close, which is slightly optimistic. No costs or slippage."},
        {"title": "Normal baseline", "text": f"The {H}-day return starting from every trading day in the same range (overlapping windows). It describes typical behaviour; it is not an independent sample."},
        {"title": "Confidence intervals", "text": "t-interval: mean ± t·s/√n (assumes roughly bell-shaped outcomes). Bootstrap: 2,000 resamples with replacement, fixed seed, middle 95% of resampled means/medians. Both describe uncertainty about the historical average, not the range of future outcomes."},
        {"title": "Outliers", "text": f"No outcome is deleted for being extreme. Trimmed mean drops the top and bottom {definition['settings']['trim']:.0%} (at least one each side when n ≥ 10); winsorized mean pulls them in instead."},
        {"title": "Definition", "text": json.dumps({k: definition[k] for k in ("instrument", "timeframe", "conditions", "logic", "outcome", "period")}, separators=(",", ":"))},
    ]


# =============================================================================
# Sample-size preview (cheap: no outcomes, no statistics)
# =============================================================================
def preview(raw_definition):
    """
    How many qualifying days and non-overlapping episodes remain as each
    condition is added, in order: shows the sample-size cost of every extra condition.
    """
    definition = normalize(raw_definition)
    horizon = definition["outcome"]["horizon"]
    steps = []
    for k in range(1, len(definition["conditions"]) + 1):
        partial = copy.deepcopy(definition)
        partial["conditions"] = definition["conditions"][:k]
        partial["logic"] = {"op": "AND", "items": [c["id"] for c in partial["conditions"]]}
        prep = prepare(partial)
        episodes, qualifying, _ = detect_triggers(prep, horizon)
        steps.append({"conditions": k, "qualifying_days": qualifying,
                      "episodes": sum(1 for e in episodes if e["status"] == "complete")})
    return {"symbol": definition["instrument"]["symbol"], "horizon": horizon, "steps": steps}


def _legacy_params(definition):
    """Flat parameters for older UI code paths (first price condition + horizon)."""
    first = next((c for c in definition["conditions"] if c["type"] == "price_move"), None)
    params = {"forward": definition["outcome"]["horizon"]}
    if first:
        params.update(direction=first["params"]["direction"], threshold=first["params"]["threshold"],
                      window=first["params"]["window"])
    return params


def summary_for_notebook(result):
    """Everything worth keeping about a run, without the per-episode data."""
    s, r, b = result.get("stats"), result.get("robust"), result.get("baseline")
    if not s:
        return {"n": 0, "ran_at": result.get("ran_at"),
                "tested_from": result["data"]["tested_from"], "tested_to": result["data"]["tested_to"]}
    return {
        "n": s["n"], "mean": s["mean"], "median": s["median"], "positive_rate": s["positive_rate"],
        "negative_rate": s["negative_rate"], "std": s["std"], "ci": [s["ci_low"], s["ci_high"]],
        "best": s["best"], "worst": s["worst"],
        "trimmed_mean": r["trimmed_mean"] if r else None,
        "winsorized_mean": r["winsorized_mean"] if r else None,
        "mean_without_extreme": r["mean_without_extreme"] if r else None,
        "bootstrap_mean_ci": r["bootstrap_mean_ci"] if r else None,
        "bootstrap_median_ci": r["bootstrap_median_ci"] if r else None,
        "baseline_mean": b["mean"] if b else None, "baseline_median": b["median"] if b else None,
        "difference": result.get("difference"),
        "baseline_inside_ci": result.get("baseline_inside_ci"),
        "checks": result.get("checks"),
        "quality": result["data"]["quality"]["summary"],
        "tested_from": result["data"]["tested_from"], "tested_to": result["data"]["tested_to"],
        "source": result["data"]["source"],
        "ran_at": result["ran_at"],
    }


# =============================================================================
# Foundations for Compare Lab and Parameter Lab (used by the UI's "Test
# elsewhere" today; parameter heat-maps will build on these).
# A definition is plain data, so "the same idea elsewhere" or "the same idea
# with a slightly different threshold" is just a modified copy.
# =============================================================================

def with_symbol(definition, symbol):
    """The same experiment on another instrument."""
    d = copy.deepcopy(definition)
    d["instrument"] = {**d.get("instrument", {}), "symbol": symbol}
    return d


def with_param(definition, path, value):
    """
    Copy of `definition` with one parameter changed. Paths:
        "horizon"                 the forward period
        "conditions.0.threshold"  a condition parameter
    """
    d = copy.deepcopy(definition)
    if path == "horizon":
        d["outcome"]["horizon"] = value
        return d
    _, index, name = path.split(".")
    d["conditions"][int(index)]["params"][name] = value
    return d


def parameter_grid(definition, axes):
    """
    Every combination of the given parameter values, e.g.
        parameter_grid(d, {"conditions.0.threshold": [5, 7.5, 10], "horizon": [5, 10, 20]})
    -> list of ({"conditions.0.threshold": 5, "horizon": 5}, definition), ...
    Running each and comparing them shows whether an apparent effect holds in a
    NEIGHBOURHOOD of parameters or only at one suspiciously specific setting.
    (Running many variants is itself a multiple-testing risk; the UI must say so.)
    """
    combos = [({}, copy.deepcopy(definition))]
    for path, values in axes.items():
        combos = [({**labels, path: v}, with_param(d, path, v)) for labels, d in combos for v in values]
    return combos
